// Appointment reminders.
//   GET  ?confirm=<token>                      → patient taps the link in the SMS; confirms the appointment
//   POST { sweep: true } + header x-cron-secret → flag missed visits, run NCD recall, then send due SMS reminders
//                                                (scheduled every 5 min by pg_cron, same secret as payments)
// SMS goes through Africa's Talking with the AT_USERNAME / AT_API_KEY secrets (optional AT_SENDER_ID),
// the same account Settings → Notifications already uses. Reminders only go out when the hospital has
// "Appointment reminder" switched on there.
import { corsHeaders, errorResponse, HttpError, json } from '../_shared/cors.ts'
import { admin, functionsBase } from '../_shared/db.ts'
import { timingSafeEqual } from '../_shared/crypto.ts'
import { normalizeKenyanPhone } from '../_shared/phone.ts'
import { buildMessage, confirmPage, parseAfricasTalking, type ReminderRow, skipReason } from './logic.ts'

const MAX_ATTEMPTS = 3

/** Scheduled MOH reports: generate what is due, then email it (Resend) when RESEND_API_KEY is set. */
async function runReports(db: ReturnType<typeof admin>) {
  const { data: generated } = await db.rpc('report_run_due').then((r) => r, () => ({ data: null }))
  const { data: pending } = await db.from('report_runs').select('id, hospital_id, form, period_from, period_to, csv, recipients')
    .eq('email_status', 'pending').order('generated_at').limit(20)
  const key = Deno.env.get('RESEND_API_KEY') || ''
  const from = Deno.env.get('REPORTS_FROM_EMAIL') || ''
  let emailed = 0
  for (const r of pending || []) {
    if (!key || !from) {
      await db.from('report_runs').update({ email_status: 'skipped', email_error: 'Email not configured (RESEND_API_KEY / REPORTS_FROM_EMAIL). Download it from Reports → MOH & KHIS.' }).eq('id', r.id)
      continue
    }
    const { data: h } = await db.from('hospitals').select('name').eq('id', r.hospital_id).maybeSingle()
    const subject = `MOH ${r.form} — ${h?.name || 'Facility'} — ${r.period_from} to ${r.period_to}`
    const res = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        from, to: r.recipients, subject,
        text: `Attached is the MOH ${r.form} summary for ${h?.name || 'the facility'} (${r.period_from} to ${r.period_to}), generated by RemedacareHMS.`,
        attachments: [{ filename: `MOH${r.form}_${r.period_from}_${r.period_to}.csv`, content: btoa(unescape(encodeURIComponent(r.csv || ''))) }],
      }),
    }).catch((e) => ({ ok: false, text: async () => String(e) }) as Response)
    if (res.ok) { emailed++; await db.from('report_runs').update({ email_status: 'sent', email_error: null }).eq('id', r.id) }
    else await db.from('report_runs').update({ email_status: 'failed', email_error: (await res.text()).slice(0, 300) }).eq('id', r.id)
  }
  return { generated: generated ?? null, emailed }
}

async function sendSms(to: string, message: string) {
  const username = Deno.env.get('AT_USERNAME') || ''
  const apiKey = Deno.env.get('AT_API_KEY') || ''
  if (!username || !apiKey) return { ok: false, error: 'SMS not configured (AT_USERNAME / AT_API_KEY secrets missing)', permanent: true }
  const host = username === 'sandbox' ? 'https://api.sandbox.africastalking.com' : 'https://api.africastalking.com'
  const form = new URLSearchParams({ username, to: '+' + to, message })
  const sender = Deno.env.get('AT_SENDER_ID')
  if (sender) form.set('from', sender)
  const res = await fetch(`${host}/version1/messaging`, {
    method: 'POST',
    headers: { apiKey, Accept: 'application/json', 'Content-Type': 'application/x-www-form-urlencoded' },
    body: form,
  })
  const body = await res.json().catch(() => ({}))
  return { ...parseAfricasTalking(body), permanent: false }
}

async function sweep(db: ReturnType<typeof admin>) {
  const { data: missed } = await db.rpc('sched_flag_missed')
  // NCD recall (overdue → tracing, LTFU after 28 days). Ignored until the NCD migration is installed.
  const { data: recall } = await db.rpc('ncd_recall_sweep').then((r) => r, () => ({ data: null }))
  // Ward MAR: doses still undocumented 4 h after their time become 'missed'.
  const { data: marMissed } = await db.rpc('mar_flag_missed').then((r) => r, () => ({ data: null }))
  const { data: due } = await db.from('appointment_reminders').select('*')
    .eq('status', 'queued').lte('due_at', new Date().toISOString()).order('due_at').limit(100)
  const hospitals = new Map<string, { name: string; enabled: boolean; template: string | null }>()
  let sent = 0, skipped = 0, failed = 0
  for (const r of (due || []) as ReminderRow[]) {
    // claim the row so two overlapping sweeps never send the same SMS twice
    const { data: claimed } = await db.from('appointment_reminders').update({ status: 'sending', attempts: r.attempts + 1 })
      .eq('id', r.id).eq('status', 'queued').select('id').maybeSingle()
    if (!claimed) continue

    if (!hospitals.has(r.hospital_id)) {
      const [{ data: h }, { data: s }] = await Promise.all([
        db.from('hospitals').select('name').eq('id', r.hospital_id).maybeSingle(),
        db.from('hospital_settings').select('notification_config').eq('hospital_id', r.hospital_id).maybeSingle(),
      ])
      const cfg = (s?.notification_config || {}) as Record<string, any>
      hospitals.set(r.hospital_id, {
        name: h?.name || 'the hospital',
        enabled: Boolean(cfg.appointment_reminder?.enabled),
        template: cfg.appointment_reminder?.template || null,
      })
    }
    const hosp = hospitals.get(r.hospital_id)!
    const { data: a } = r.kind === 'offer' ? { data: null } : await db.from('appointments')
      .select('status, starts_at, doctor_name, patients(full_name)').eq('id', r.appointment_id).maybeSingle()
    const appt = a ? { status: a.status, starts_at: a.starts_at, doctor_name: a.doctor_name, patient_name: (a as any).patients?.full_name } : null

    const why = skipReason(r, appt, hosp.enabled)
    if (why) {
      await db.from('appointment_reminders').update({ status: 'skipped', last_error: why }).eq('id', r.id)
      skipped++
      continue
    }
    const message = buildMessage(r, appt, { hospitalName: hosp.name, template: hosp.template, confirmBase: `${functionsBase()}/appointments-reminders` })
    try {
      const out = await sendSms(normalizeKenyanPhone(r.phone)!, message)
      if (out.ok) {
        await db.from('appointment_reminders').update({ status: 'sent', sent_at: new Date().toISOString(), message, last_error: null }).eq('id', r.id)
        sent++
      } else {
        const retry = !out.permanent && r.attempts + 1 < MAX_ATTEMPTS
        await db.from('appointment_reminders').update({
          status: retry ? 'queued' : 'failed', last_error: out.error,
          ...(retry ? { due_at: new Date(Date.now() + 10 * 60e3).toISOString() } : {}),
        }).eq('id', r.id)
        failed++
      }
    } catch (e) {
      await db.from('appointment_reminders').update({ status: 'queued', last_error: (e as Error).message }).eq('id', r.id)
      failed++
    }
  }
  const reports = await runReports(db).catch((e) => ({ error: (e as Error).message }))
  return { missed_flagged: missed ?? 0, ncd_recall: recall ?? null, mar_missed: marMissed ?? null, reports, due: due?.length || 0, sent, skipped, failed }
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders })
  try {
    const db = admin()
    const url = new URL(req.url)
    const token = url.searchParams.get('confirm')
    if (req.method === 'GET' && token) {
      const { data } = await db.rpc('sched_confirm_by_token', { p_token: token })
      const res = (data || {}) as { ok?: boolean; error?: string; date?: string; time?: string; doctor?: string }
      const text = res.ok
        ? `Thank you. Your appointment on ${res.date} at ${res.time}${res.doctor ? ` with ${res.doctor}` : ''} is confirmed.`
        : (res.error || 'This link is not valid.')
      return new Response(confirmPage(Boolean(res.ok), text), { status: res.ok ? 200 : 400, headers: { 'Content-Type': 'text/html; charset=utf-8' } })
    }

    const b = await req.json().catch(() => ({}))
    if (!b.sweep) throw new HttpError(400, 'Nothing to do')
    const secret = Deno.env.get('PAYMENTS_CRON_SECRET') || ''
    if (secret.length < 16 || !timingSafeEqual(secret, req.headers.get('x-cron-secret') || '')) throw new HttpError(401, 'Unauthorised')
    return json({ success: true, ...(await sweep(db)) })
  } catch (e) {
    return errorResponse(e)
  }
})
